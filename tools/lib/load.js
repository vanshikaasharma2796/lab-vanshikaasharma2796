/* =====================================================================
   tools/lib/load.js — load the app under Node, the way the page loads it

   The page pulls in plain <script> files in the order index.html lists
   them. This does the same under Node (minus the page itself), so the
   command-line tools run exactly the code and data the browser runs.

     const { MCX, openWarehouse } = require('./lib/load');
     await openWarehouse();
   ===================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..', '..');

/** The <script src> list from index.html, minus the vendor files and the page code. */
function scriptList() {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const all = [];
  html.replace(/<script\s+src="([^"]+)"/g, (m, src) => { all.push(src); return m; });
  return all.filter((src) => !src.startsWith('vendor/') && src !== 'src/app.js' && !src.startsWith('src/ui/'));
}

globalThis.window = globalThis;
if (typeof globalThis.atob !== 'function') globalThis.atob = (text) => Buffer.from(text, 'base64').toString('binary');

const loaded = scriptList();
loaded.forEach((file) => {
  // evals/bundle.js is generated by tools/golden.js --update; the tools still start without it.
  if (file === 'evals/bundle.js' && !fs.existsSync(path.join(root, file))) { globalThis.MCX.evalBundle = { set: [], golden: [] }; return; }
  try {
    vm.runInThisContext(fs.readFileSync(path.join(root, file), 'utf8'), { filename: file });
  } catch (error) {
    // One broken analysis file should not stop the tools from checking the others.
    if (!file.startsWith('src/analyses/')) throw error;
    console.error('!! ' + file + ' did not load: ' + error.message);
  }
});

const MCX = globalThis.MCX;

/** Build the warehouse with the vendored sql.js. Resolves with the load statistics. */
function openWarehouse() {
  const initSqlJs = require(path.join(root, 'vendor', 'sqljs', 'sql-wasm.js'));
  const wasmBinary = fs.readFileSync(path.join(root, 'vendor', 'sqljs', 'sql-wasm.wasm'));
  return MCX.db.open({ initSqlJs, wasmBinary });
}

module.exports = { MCX, root, loaded, openWarehouse };
